public class TaskTwentythree{
    public static void main(String[] args){

        int score = 71;

        if (score >= 90){
            System.out.println("A (90-100)");
        }
        else if (score >= 89){
            System.out.println("B (80-89)");
        }
        else if (score >= 79){
            System.out.println("C (70-79)");
        }
        else if (score >= 69){
            System.out.println("D (60-69)");
        }
        else if (score <= 60){
            System.out.println("F (below 60)");
        }

}}
